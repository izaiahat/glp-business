#: Match strengths, strongest first. A weaker match never beats a stronger one,
#: which is what stops a site program from being pinned to a same-named row that
#: is really a different relationship (proven on the real Sheet: `found-health`
#: matches row 110 by Katalys offer id AND row 19 by name; row 110 is the truth).
MATCH_NETWORK_PROGRAM_ID = 3
MATCH_TRACKING_LINK = 2
MATCH_PROGRAM_NAME = 1
MATCH_LABEL = {
    MATCH_NETWORK_PROGRAM_ID: "network_program_id",
    MATCH_TRACKING_LINK: "tracking_link",
    MATCH_PROGRAM_NAME: "program_name",
}


def sheet_row_identity(padded: list[Any]) -> dict[str, str]:
    return {
        "program_name": str(padded[COL_PROGRAM]).strip(),
        "network": str(padded[COL_NETWORK]).strip(),
        "program_id": writer.offer_from_url(padded[COL_APPLY_URL]),
        "tracking": str(padded[COL_TRACKING] or "").strip(),
    }


def match_site_programs(
    rows: dict[int, dict[str, Any]], site_programs: dict[str, dict[str, Any]],
) -> tuple[dict[int, dict[str, Any]], list[dict[str, Any]]]:
    """Pin each SITE program to at most one Sheet row, strongest match wins.

    Site-program-centric on purpose: a site program has exactly one honest home
    row, and doing it row-centric would let two rows both call themselves live.
    """
    assignments: dict[int, dict[str, Any]] = {}
    ambiguous: list[dict[str, Any]] = []
    for program_id, program in sorted(site_programs.items()):
        network = norm(program.get("network"))
        network_program_id = str(program.get("network_program_id") or "").strip().casefold()
        display = norm(program.get("display_name"))
        candidates: list[tuple[int, int]] = []
        for row_num, row in rows.items():
            identity = row["identity"]
            strength = 0
            if (network_program_id and network
                    and norm(identity["network"]) == network
                    and identity["program_id"].casefold() == network_program_id):
                strength = MATCH_NETWORK_PROGRAM_ID
            elif network_program_id and identity["tracking"] and re.search(
                    r"(?<![0-9a-z])" + re.escape(network_program_id) + r"(?![0-9a-z])",
                    identity["tracking"].casefold()):
                strength = MATCH_TRACKING_LINK
            elif display and norm(identity["program_name"]) == display:
                strength = MATCH_PROGRAM_NAME
            if strength:
                candidates.append((strength, row_num))
        if not candidates:
            ambiguous.append({"program": program_id, "reason": "no_sheet_row_matches",
                              "display_name": program.get("display_name"),
                              "on_live_site": program.get("on_live_site"),
                              "monetized_on_site": bool(program.get("monetized_on_site")
                                                        or program.get("on_live_site"))})
            continue
        best = max(strength for strength, _ in candidates)
        winners = sorted(row_num for strength, row_num in candidates if strength == best)
        if len(winners) > 1:
            ambiguous.append({"program": program_id, "reason": "sheet_row_ambiguous",
                              "rows": winners, "match": MATCH_LABEL[best],
                              "on_live_site": program.get("on_live_site"),
                              "monetized_on_site": bool(program.get("monetized_on_site")
                                                        or program.get("on_live_site"))})
            continue
        assignments[winners[0]] = {
            "program": program_id,
            "match": MATCH_LABEL[best],
            "display_name": program.get("display_name"),
            "on_live_site": bool(program.get("on_live_site")),
            "monetized_review_cta": bool(program.get("monetized_review_cta")),
            "monetized_on_site": bool(program.get("monetized_on_site")
                                      or program.get("on_live_site")),
            "review_cta": program.get("review_cta"),
            "in_release_registry": bool(program.get("in_release_registry")),
            "in_release_go_manifest": bool(program.get("in_release_go_manifest")),
            "review_path": program.get("review_path"),
            "surfaces": program.get("surfaces") or {},
        }
    return assignments, ambiguous


