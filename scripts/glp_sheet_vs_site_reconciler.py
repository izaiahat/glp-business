def read_sheet() -> list[list[Any]]:
    """The governed Sheet, read through the same auth path the writer uses."""
    from googleapiclient.discovery import build as _build

    svc = _build("sheets", "v4", credentials=writer.creds(), cache_discovery=False)
    values = svc.spreadsheets().values().get(
        spreadsheetId=writer.SHEET_ID,
        range=f"'{writer.TAB}'!{EXPECTED_RANGE}",
        valueRenderOption="UNFORMATTED_VALUE",
    ).execute().get("values", [])
    if not values or writer.pad(values[0]) != writer.HEADERS:
        raise SystemExit("canonical_header_mismatch:refusing_to_reconcile")
    return values


