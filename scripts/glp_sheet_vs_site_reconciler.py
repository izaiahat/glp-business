#: Any single HTML start tag. The review pages are machine-generated, so a tag
#: never contains a raw `<` or `>`; this is deliberately not an HTML parser
#: because the only thing it has to find is one generated element.
HTML_TAG_RE = re.compile(r"<[a-zA-Z][a-zA-Z0-9-]*\b[^<>]*>")


def _attr(tag: str, name: str) -> str | None:
    match = re.search(r"\b" + re.escape(name) + r"\s*=\s*\"([^\"]*)\"", tag)
    return unescape(match.group(1)) if match else None


def base_domain(host: str) -> str:
    """`www.awin1.com` -> `awin1.com`, so an allowlist entry covers its subdomains."""
    host = str(host or "").strip().lower().rstrip(".")
    return host[4:] if host.startswith("www.") else host


def read_tracking_host_allowlist(release: Path) -> dict[str, Any]:
    """Read the renderer's per-program projection of the canonical rail hosts.

    New releases carry ``data/tracking-allowed-hosts.json``, regenerated on each
    build by ``glp_affiliate_link_rails.program_allowed_hosts``. Older releases
    predate that projection and retain the approved-registry fallback so their
    historical CTAs remain auditable without pretending they have newer bytes.
    """
    derived_path = Path(release) / TRACKING_ALLOWED_HOSTS_REL
    per_program: dict[str, Any] = {}
    sources: list[str] = []
    projection_error = None
    try:
        derived = json.loads(derived_path.read_text())
        if derived.get("schema") != "glp.tracking_allowed_hosts.v1":
            raise ValueError("tracking_allowed_hosts_schema_invalid")
        per_program = derived.get("programs") or {}
        if not isinstance(per_program, dict):
            raise ValueError("tracking_allowed_hosts_programs_invalid")
        sources.append(repo_relative(derived_path))
    except Exception as exc:  # noqa: BLE001 - fallback is named in the receipt
        projection_error = f"{type(exc).__name__}: {exc}"

    path = Path(release) / APPROVED_REGISTRY_REL
    hosts_map: dict[str, Any] = {}
    try:
        payload = json.loads(path.read_text())
        hosts_map = payload.get("allowed_provider_tracking_hosts") or {}
    except Exception as exc:  # noqa: BLE001 - an unreadable fallback is reported
        if not per_program:
            projection_error = f"{type(exc).__name__}: {exc}"

    domains: set[str] = set()
    for entry in per_program.values():
        if not isinstance(entry, dict):
            continue
        for host in entry.get("allowed_hosts") or []:
            if base_domain(host):
                domains.add(base_domain(host))
    for hosts in hosts_map.values():
        for host in hosts or []:
            if base_domain(host):
                domains.add(base_domain(host))
    if not per_program and domains:
        sources.append(repo_relative(path))
    if not domains:
        domains.update(FALLBACK_TRACKING_HOSTS)
        sources.append("builtin_fallback")
    domains.update(CJ_CLICK_HOSTS)
    sources.append("cj_click_hosts")
    return {"domains": sorted(domains), "sources": sources,
            "networks": sorted(hosts_map), "programs": per_program,
            # A historical release with a readable approved-registry fallback is
            # healthy for its own byte era. Preserve the missing-projection fact
            # separately without turning that expected fallback into an error.
            "projection_error": projection_error,
            "error": projection_error if not per_program and not hosts_map else None}


def read_tracking_link_contracts(release: Path) -> dict[str, dict[str, Any]]:
    """Program link specs used to validate rendered transparent-direct CTAs.

    This is data, not rail vocabulary. Network shape, required attribution
    parameters and allowed-host resolution stay in ``glp_affiliate_link_rails``.
    """
    path = Path(release) / PROVIDER_CONTRACTS_REL
    try:
        payload = json.loads(path.read_text())
    except Exception:  # noqa: BLE001 - absent on historical releases
        return {}
    out: dict[str, dict[str, Any]] = {}
    for item in payload.get("providers") or []:
        if not isinstance(item, dict):
            continue
        program_id = str(item.get("program_id") or "").strip()
        network_contract = item.get("network_contract") or {}
        row_contract = item.get("row_contract") or {}
        network = str(network_contract.get("network") or "").strip()
        expected_href = str(row_contract.get("affiliate_href") or "").strip()
        if not program_id or not network or not expected_href:
            continue
        out[program_id] = {
            "program_id": program_id,
            "network": network,
            "immutable_id": str(network_contract.get("immutable_offer_id") or "").strip(),
            "official_url": item.get("official_url"),
            "tracking_host": item.get("tracking_host"),
            "tracking_form": str(network_contract.get("tracking_form")
                                 or row_contract.get("tracking_form") or ""),
            "expected_href": expected_href,
            "source": repo_relative(path),
        }

    # This is the same two-input merge used by emit-tracking-allowed-hosts.py:
    # provider contracts carry independently authored official URLs and immutable
    # rail ids; money-page rows carry the declared per-program tracking host/form.
    # The verifier therefore validates the exact same program record whose
    # canonical host projection the renderers consume, rather than reconstructing
    # a narrower fourth copy from provider contracts alone.
    money_path = Path(release) / MONEY_PAGE_SPECS_REL
    try:
        money = json.loads(money_path.read_text())
    except Exception:  # noqa: BLE001 - absent on historical review-only releases
        money = {}
    for page in money.get("pages") or []:
        for row in page.get("rows") or []:
            if not isinstance(row, dict):
                continue
            program_id = str(row.get("program_id") or "").strip()
            network = str(row.get("affiliate_network") or "").strip()
            expected_href = str(row.get("affiliate_href") or "").strip()
            if not program_id or not network or not expected_href:
                continue
            contract = out.setdefault(program_id, {
                "program_id": program_id,
                "network": network,
                "immutable_id": "",
                "official_url": row.get("official_url"),
                "tracking_host": None,
                "tracking_form": "",
                "expected_href": expected_href,
                "source": repo_relative(money_path),
            })
            if str(contract.get("network") or "").casefold() != network.casefold():
                # Leave the conflict visible: the canonical network-projection
                # comparison below will refuse it by name.
                contract["network_conflict"] = network
            contract["official_url"] = contract.get("official_url") or row.get("official_url")
            contract["tracking_host"] = (contract.get("tracking_host")
                                         or row.get("affiliate_tracking_host"))
            contract["tracking_form"] = (contract.get("tracking_form")
                                         or row.get("affiliate_tracking_form") or "")
            if repo_relative(money_path) not in str(contract.get("source") or ""):
                contract["source"] = f"{contract.get('source')} + {repo_relative(money_path)}"
    return out


def is_affiliate_tracking_host(host: str | None, domains: list[str] | tuple[str, ...]) -> bool:
    host = base_domain(host or "")
    if not host:
        return False
    return any(host == domain or host.endswith("." + domain) for domain in domains)


def read_redirect_map(release: Path) -> dict[str, str]:
    """Exact-path 30x rules from the deployed `_redirects`. Wildcards are skipped.

    A splat/placeholder rule cannot be resolved without the request that matched
    it, and guessing one would let this job claim a page a reader never sees.
    """
    path = Path(release) / REDIRECTS_REL
    mapping: dict[str, str] = {}
    if not path.is_file():
        return mapping
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) < 2:
            continue
        source, target = parts[0], parts[1]
        if not source.startswith("/") or "*" in source or ":" in source:
            continue
        mapping.setdefault(source, target)
    return mapping


def resolve_route(route: str, redirects: dict[str, str]) -> str:
    seen: set[str] = set()
    for _ in range(REDIRECT_MAX_HOPS):
        if route in redirects and route not in seen:
            seen.add(route)
            route = redirects[route]
            continue
        break
    return route


def read_canonical_identity(release: Path, profile: str = SITE_PROFILE) -> dict[str, dict[str, Any]]:
    """program_id -> its review route and its declared canonical-identity alias."""
    path = Path(release) / PROGRAM_REGISTRY_REL
    try:
        registry = json.loads(path.read_text())
    except Exception:  # noqa: BLE001
        return {}
    index: dict[str, dict[str, Any]] = {}
    for row in registry.get("programs") or []:
        program_id = str(row.get("program_id") or "").strip()
        if not program_id:
            continue
        block = (row.get("profiles") or {}).get(profile) or {}
        identity = block.get("canonical_identity") or {}
        canonical = str(identity.get("canonical_program_id") or "").strip()
        index[program_id] = {
            "review_path": row.get("review_path"),
            "canonical_program_id": canonical or None,
            "role": identity.get("role"),
        }
    return index


def rendered_review_page(release: Path, program_id: str, review_path: str | None,
                         canonical: dict[str, dict[str, Any]],
                         redirects: dict[str, str]) -> dict[str, Any] | None:
    """The review page a READER lands on for this program, as a file on disk.

    Candidates, in order: the program's own review route, then - only when the
    registry itself declares this program an alias - the canonical merchant
    record's route. Each is walked through the release's redirect map first.
    """
    candidates: list[tuple[str, str]] = []
    if review_path:
        candidates.append((str(review_path), "review_path"))
    entry = canonical.get(program_id) or {}
    canonical_id = entry.get("canonical_program_id")
    if canonical_id and canonical_id != program_id:
        canonical_route = (canonical.get(canonical_id) or {}).get("review_path")
        if canonical_route:
            candidates.append((str(canonical_route), "canonical_identity_alias"))

    for route, kind in candidates:
        resolved = resolve_route(route, redirects)
        if not resolved.startswith(REVIEW_ROUTE_PREFIX):
            continue
        page = Path(release) / PUBLIC_REL / resolved.strip("/") / "index.html"
        if not page.is_file():
            continue
        return {
            "review_route": route,
            "resolved_route": resolved,
            "resolution": kind if resolved == route else f"{kind}+redirect",
            "page_path": page,
        }
    return None


def _affiliate_element_attributes(tag: str) -> dict[str, Any]:
    return {
        "state": str(_attr(tag, "data-affiliate-state") or "").strip().lower(),
        "href": _attr(tag, "href"),
        "link_mode": _attr(tag, "data-link-mode"),
        "analytics_event": _attr(tag, "data-analytics-event"),
        "data_program": _attr(tag, "data-program"),
        "data_network": (_attr(tag, "data-network")
                         or _attr(tag, "data-affiliate-network")),
        "classes": sorted(set((_attr(tag, "class") or "").split())),
        "rel": sorted(set((_attr(tag, "rel") or "").split())),
    }


def affiliate_anchor_element(tag: str) -> dict[str, Any] | None:
    """Parse one affiliate anchor into exact attributes and token-list fields.

    ``rel`` and ``class`` are HTML token lists. Their serialized order differs
    between the provider-detail and review renderers, so callers compare sets,
    never the joined attribute string. This parser does not decide whether an
    anchor earns; the registry-bound validator below owns that decision.
    """
    if not re.match(r"<a\b", str(tag or ""), re.IGNORECASE):
        return None
    return _affiliate_element_attributes(tag)


def cta_elements(html: str) -> list[dict[str, Any]]:
    """Every rendered element that declares an affiliate state, with its href."""
    found: list[dict[str, Any]] = []
    for tag in HTML_TAG_RE.findall(html):
        if _attr(tag, "data-affiliate-state") is None:
            continue
        found.append(_affiliate_element_attributes(tag))
    return found


def validate_registry_affiliate_element(
    element: dict[str, Any], contract: dict[str, Any],
    derived_entry: dict[str, Any] | None, *, surface: str,
) -> dict[str, Any]:
    """Validate a rendered CTA through exact registry and rail facts, without I/O."""
    classes = set(element.get("classes") or [])
    rel = set(element.get("rel") or [])
    required_classes = (CTA_CLASS_MARKERS if surface == "review"
                        else PROVIDER_CTA_CLASS_MARKERS if surface == "provider"
                        else frozenset())
    if not required_classes:
        return {"ok": False, "error": f"affiliate_anchor_surface_invalid:{surface}"}
    missing_classes = sorted(required_classes - classes)
    missing_rel = sorted(CTA_REL_MARKERS - rel)
    if surface == "review" and str(element.get("state") or "") != CTA_ACTIVE_STATE:
        return {"ok": False, "error": "transparent_direct_state_not_active"}
    if (surface == "review"
            and str(element.get("link_mode") or "").casefold() != "transparent-direct"):
        return {"ok": False, "error": "transparent_direct_link_mode_missing"}
    if missing_classes or missing_rel:
        return {
            "ok": False,
            "error": "transparent_direct_markers_missing",
            "missing_classes": missing_classes,
            "missing_rel": missing_rel,
        }
    if str(element.get("analytics_event") or "") != "affiliate_click":
        return {"ok": False, "error": "affiliate_click_analytics_marker_missing"}
    if str(element.get("data_program") or "") != str(contract.get("program_id") or ""):
        return {"ok": False, "error": "transparent_direct_program_marker_drift"}
    rendered_network = str(element.get("data_network") or "").casefold()
    contract_network = str(contract.get("network") or "").casefold()
    # The site's provider-hosted affiliate form is intentionally rendered as
    # `data-network="direct"`; Trackdesk remains the canonical rail behind that
    # form. The alias is accepted only for Trackdesk and only after the exact
    # registry href and Trackdesk tuple validate below.
    provider_hosted_trackdesk = contract_network == "trackdesk" and rendered_network == "direct"
    if rendered_network != contract_network and not provider_hosted_trackdesk:
        return {"ok": False, "error": "transparent_direct_network_marker_drift"}
    if contract.get("network_conflict"):
        return {"ok": False, "error": "tracking_contract_network_conflict"}
    href = str(element.get("href") or "")
    network = str(contract.get("network") or "")
    spec = {
        "official_url": contract.get("official_url"),
        "tracking_host": contract.get("tracking_host"),
    }
    try:
        allowed_hosts = set(link_rails.program_allowed_hosts(network, spec))
        if not isinstance(derived_entry, dict):
            raise link_rails.RailError("tracking_allowed_hosts_program_underived")
        if rc_network := str(derived_entry.get("network") or ""):
            if rc_network.casefold() != network.casefold():
                raise link_rails.RailError("tracking_allowed_hosts_network_drift")
        emitted_hosts = {str(host).casefold()
                         for host in (derived_entry.get("allowed_hosts") or [])}
        if emitted_hosts != allowed_hosts:
            raise link_rails.RailError("tracking_allowed_hosts_projection_drift")
        host = (urlsplit(href).hostname or "").casefold()
        if host not in allowed_hosts:
            raise link_rails.RailError(f"rendered_tracking_host_not_allowed:{host}")
        immutable_id = str(contract.get("immutable_id") or "")
        rail = link_rails.rail_for(network)
        tracking_form = str(contract.get("tracking_form") or "")
        # A Direct-affiliate contract can use one of multiple canonical forms.
        # Old provider records did not name which one; exact-template comparison
        # is stricter than guessing a form. Every other verified rail has one
        # structural validator, including Trackdesk's required
        # linkId/sourceId/tenantId tuple.
        structurally_validatable = bool(immutable_id and rail
                                        and (rail.network != "Direct affiliate"
                                             or tracking_form))
        if structurally_validatable:
            allowed_host = (link_rails.spec_allowed_host(network, spec)
                            if rail and not rail.hosts else None)
            link_rails.validate_link(
                network, immutable_id, href, allowed_host=allowed_host,
                tracking_form=tracking_form or "query_offer_publisher",
            )
            validation = "canonical_rail_validator"
        elif href != str(contract.get("expected_href") or ""):
            # Some historical provider contracts (notably CJ) record an exact
            # issued link but not the rail's URL-carried immutable id. Preserve
            # that exact template rather than guessing an id out of the href.
            raise link_rails.RailError("rendered_tracking_template_drift")
        else:
            validation = "recorded_href_template"
        if href != str(contract.get("expected_href") or ""):
            # Structural validity is necessary but not sufficient. The rendered
            # provider-hosted URL must be the exact issued href stored in the
            # release registry; a different valid-looking Trackdesk link cannot
            # inherit this provider's approval.
            raise link_rails.RailError("rendered_tracking_href_registry_drift")
    except (link_rails.RailError, ValueError) as exc:
        return {"ok": False, "error": str(exc)}
    return {
        "ok": True,
        "error": None,
        "rail": (link_rails.rail_for(network).network
                 if link_rails.rail_for(network) else network),
        "validation": validation,
        "allowed_hosts": sorted(allowed_hosts),
        "markers_valid": True,
        "surface": surface,
        "contract_source": contract.get("source"),
    }


def validate_transparent_direct_element(
    element: dict[str, Any], contract: dict[str, Any],
    derived_entry: dict[str, Any] | None,
) -> dict[str, Any]:
    """Validate one review-page CTA through the canonical rail record."""
