def latest_wire_backlog_plan(root: Path = WIRE_BACKLOG_DAILY) -> dict[str, Any]:
    """The most recent B2 wire-backlog plan - the deploy machine's own queue."""
    root = Path(root)
    if not root.is_dir():
        return {}
    for day in sorted((p for p in root.iterdir() if p.is_dir()), reverse=True):
        plan = day / "plan.json"
        if plan.is_file():
            payload = read_json(plan)
            payload["_path"] = repo_relative(plan)
            return payload
    return {}


def scan_evidence_receipts(roots: tuple[Path, ...] = EVIDENCE_ROOTS) -> dict[str, list[dict]]:
    """Find on-disk receipts whose schema a governed mode will accept as evidence."""
    found: dict[str, list[dict]] = {DEPLOY_VERIFICATION_SCHEMA: [], REMOVAL_RECEIPT_SCHEMA: []}
    seen = 0
    for root in roots:
        root = Path(root)
        if not root.is_dir():
            continue
        for path in sorted(root.rglob("*.json")):
            seen += 1
            if seen > EVIDENCE_SCAN_MAX_FILES:
                break
            try:
                payload = json.loads(path.read_text())
            except Exception:  # noqa: BLE001 - a broken file is not evidence
                continue
            if not isinstance(payload, dict):
                continue
            schema = payload.get("schema")
            if schema in found:
                payload = dict(payload)
                payload["_path"] = repo_relative(path)
                found[schema].append(payload)
    return found


