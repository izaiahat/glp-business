def malformations(row: dict[str, Any]) -> list[str]:
    """Schema problems that make a row's own claims untrustworthy."""
    padded = row["padded"]
    issues: list[str] = []
    if not str(padded[COL_PROGRAM]).strip():
        issues.append("program_name_blank")
    if not row["status"]:
        issues.append("status_blank")
    vertical = str(padded[COL_VERTICAL]).strip()
    if vertical and vertical not in VERTICAL_ALLOWED_VALUES:
        issues.append(f"vertical_not_in_vocabulary:{vertical}")
    if truthy(padded[COL_WIRED_LIVE]) and not str(padded[COL_TRACKING] or "").strip():
        issues.append("wired_live_true_without_tracking_link")
    if row["approval_claim"] and not str(padded[COL_NETWORK]).strip():
        issues.append("approval_claim_without_network")
    return issues


def is_approval_claim(status: str, program_name: str) -> bool:
    if norm(program_name) in MARKETPLACE_PARENTS:
        return False
    if status.startswith(ACCOUNT_LEVEL_STATUS_PREFIXES):
        return False
    return status.startswith(APPROVAL_CLAIM_PREFIXES)


#: The site's own vertical. Everything else in-scope is a sister vertical - the
#: deploy machine routes those to `sister_dark` rather than onto this site, so
#: naming the difference keeps a MISSED-DEPLOY triageable instead of alarming.
CORE_VERTICAL = "glp1-weightloss"


def fit_class(vertical: str) -> str:
    if vertical == CORE_VERTICAL:
        return "core_glp1"
    if vertical == OUT_OF_SCOPE_VERTICAL:
        return "out_of_scope"
    if vertical:
        return "sister_vertical"
    return "unassessed"


def build_rows(values: list[list[Any]]) -> dict[int, dict[str, Any]]:
    rows: dict[int, dict[str, Any]] = {}
    for row_num, raw in enumerate(values[1:], 2):
        padded = writer.pad(raw)
        if not writer.row_has_business_value(padded):
            continue
        status = str(padded[COL_STATUS]).strip()
        program_name = str(padded[COL_PROGRAM]).strip()
        rows[row_num] = {
            "row": row_num,
            "padded": padded,
            "status": status,
            "program": program_name,
            "identity": sheet_row_identity(padded),
            "approval_claim": is_approval_claim(status, program_name),
            "claims_live": status in LIVE_CLAIM_STATUS or truthy(padded[COL_WIRED_LIVE]),
            "fit_reason": str(padded[COL_FIT_REASON]).strip(),
            "vertical": str(padded[COL_VERTICAL]).strip(),
            "fit_class": fit_class(str(padded[COL_VERTICAL]).strip()),
            "wire_in_ready": truthy(padded[COL_WIRE_IN_READY]),
        }
    return rows


def classify_row(row: dict[str, Any], site_match: dict[str, Any] | None,
                 ctx: dict[str, Any]) -> dict[str, Any]:
    padded = row["padded"]
    on_live_site = bool(site_match and site_match.get("on_live_site"))
    review_cta = (site_match or {}).get("review_cta") or {}
    monetized_review_cta = bool(site_match and site_match.get("monetized_review_cta"))
    # The money question. `on_live_site` alone re-flagged five earning programs
    # every week; see the module docstring.
    monetized = on_live_site or monetized_review_cta
    surfaces = (site_match or {}).get("surfaces") or {}
    result: dict[str, Any] = {
        "row": row["row"],
        "program": row["program"],
        "network": row["identity"]["network"],
        "program_id": row["identity"]["program_id"] or None,
        "status": row["status"],
        "vertical": row["vertical"] or None,
        "fit_class": row["fit_class"],
        "wire_in_ready": row["wire_in_ready"],
        "wired_live_flag": truthy(padded[COL_WIRED_LIVE]),
        "approval_claim": row["approval_claim"],
        "site_program": (site_match or {}).get("program"),
        "site_match": (site_match or {}).get("match"),
        "site_review_path": (site_match or {}).get("review_path"),
        "site_surfaces": surfaces,
        "on_live_site": on_live_site,
        "monetized_review_cta": monetized_review_cta,
        "monetized_on_site": monetized,
        "monetization_signal": ("go_manifest" if on_live_site
                                else "review_cta" if monetized_review_cta else None),
        "review_cta": review_cta or None,
        "in_release_registry": bool(site_match and site_match.get("in_release_registry")),
        "in_release_go_manifest": bool(site_match and site_match.get("in_release_go_manifest")),
        "classification": CONSISTENT,
        "need_code": None,
        "needs": None,
        "accounted_by": None,
        "issues": [],
        "queue_row": None,
    }

    issues = malformations(row)
    if issues:
        result["classification"] = BLANK_MALFORMED
        result["issues"] = issues
        result["need_code"] = f"malformed:{issues[0]}"
        result["needs"] = "repair the row schema: " + ", ".join(issues)
        return result

    if row["claims_live"] and not monetized:
        result["classification"] = STALE_STATUS
        # Be precise about WHICH surface is missing. The 2026-08-18 first
        # production run found seven rows claiming wired-live whose review page
        # is live but whose /go affiliate route is not wired at all - the reader
        # sees a provider and the outbound link earns nothing. "Absent from the
        # site" would have been the wrong sentence and the wrong fix.
        if (review_cta.get("state") == CTA_ACTIVE_STATE
                and not review_cta.get("tracking_host_allowlisted")):
            # An active CTA we cannot attribute to any known network. Never
            # counted as earning, and never silently dropped either.
            result["need_code"] = "stale_review_cta_unrecognized_tracking_host"
            result["issues"].append("review_cta_host_not_in_affiliate_allowlist")
            detail = (f"review page {review_cta.get('resolved_route')} carries an ACTIVE "
                      f"affiliate CTA but its href host {review_cta.get('tracking_host')!r} "
                      "is not a known affiliate-network tracking host, and there is no /go "
                      "route either - attribution is unproven")
        elif review_cta.get("state") and review_cta.get("state") != CTA_ACTIVE_STATE:
            result["need_code"] = "stale_review_cta_held"
            detail = (f"review page {review_cta.get('resolved_route')} is live but its "
                      f"affiliate CTA is data-affiliate-state=\"{review_cta.get('state')}\" "
                      "(de-linked) and there is no /go route - the page earns nothing")
        elif surfaces.get("review") and not site_match.get("in_release_go_manifest"):
            result["need_code"] = "stale_review_live_go_route_unwired"
            detail = (f"review page {site_match.get('review_path')} IS live but the /go "
                      "affiliate route is not wired (registry surfaces.go=false) and the "
                      "program is absent from the deployed /go manifest")
        elif site_match and site_match.get("in_release_registry"):
            result["need_code"] = "stale_in_release_not_deployed"
            detail = "in the release registry but absent from the deployed /go manifest"
        else:
            result["need_code"] = "stale_absent_from_site"
            detail = "absent from the site program set entirely"
        if (truthy(padded[COL_WIRED_LIVE])
                and row["status"] in DEPLOYED_LIVE_SOURCE_STATUS):
            result["issues"].append("wired_live_checkbox_contradicts_status")
            detail += (f"; the Wired Live? checkbox is TRUE while Status reads "
                       f"{row['status']}")
        evidence = find_removal_receipt(row, ctx["removal_receipts"])
        if evidence and row["status"] in REMOVED_SOURCE_STATUS:
            result["queue_row"] = ("removed", evidence)
            result["need_code"] = "queued_removed"
            result["needs"] = (f"Sheet claims live; {detail}. Queued `removed` citing "
                               f"{evidence['removal_receipt_path']}.")
        else:
            reason = ("no glp.site_paused_program_removal.v1 receipt names this row"
                      if not evidence
                      else f"status {row['status']} is outside the removed mode's source set")
            result["needs"] = (f"Sheet claims live; {detail}. No governed correction can be "
                               f"queued: {reason} - deploy or removal decision required.")
        return result

    if monetized and not row["claims_live"]:
        result["classification"] = GHOST
        evidence = find_deploy_verification(row, site_match or {}, ctx["deploy_receipts"])
        link_qa = str(padded[COL_LINK_QA]).strip()
        blockers = []
        if row["status"] not in DEPLOYED_LIVE_SOURCE_STATUS:
            blockers.append(f"status {row['status']} outside deployed_live source set")
        if not str(padded[COL_TRACKING] or "").strip():
            blockers.append("no provider-issued tracking link on the row")
        if DEPLOYED_LIVE_ALLOWED_LINK_QA and link_qa not in DEPLOYED_LIVE_ALLOWED_LINK_QA:
            blockers.append(f"Link QA Status {link_qa or '(blank)'} outside allowed set")
        if not evidence:
            blockers.append("no glp.deploy_live_verification.v1 receipt with sensor_status "
                            "PASS names this program")
        else:
            missing = [key for key, _ in writer.SHEET_SYNC_MODES["deployed_live"].evidence_fields
                       if evidence.get(key) in (None, "")]
            if missing:
                blockers.append("deployed_live evidence missing: " + ", ".join(missing))
            else:
                try:
                    writer.deployed_live_tuple({
                        "network": row["identity"]["network"],
                        "provider_program_id": row["identity"]["program_id"],
                        "program": row["identity"]["program_name"],
                        "row": row["row"], "provider_slug": evidence["provider_slug"],
                        "stable_key": evidence["stable_key"],
                        "tuple_sha256": evidence["tuple_sha256"], "evidence": evidence,
                    })
                except RuntimeError as exc:
                    blockers.append("deployed_live evidence invalid: " + str(exc))
        result["need_code"] = ("ghost_no_deploy_verification_receipt" if not evidence
                               else "ghost_row_preconditions_unmet")
        if not blockers:
            result["queue_row"] = ("deployed_live", evidence)
            result["need_code"] = "queued_deployed_live"
            result["needs"] = (f"live on site as {result['site_program']} but Sheet says "
                               f"{row['status']}. Queued `deployed_live` citing "
                               f"{evidence['deploy_receipt_path']}.")
        else:
            result["needs"] = (f"live on site as {result['site_program']} but Sheet says "
                               f"{row['status']}; no governed correction queued ("
                               + "; ".join(blockers) + ")")
        return result

    if monetized and row["claims_live"]:
        result["accounted_by"] = {
            "kind": "live",
            "source": "go_manifest" if on_live_site else "review_cta",
            "reason": (f"live on site as {result['site_program']}" if on_live_site else
                       f"earning on site as {result['site_program']} through the "
                       f"transparent-direct CTA on {review_cta.get('resolved_route')} "
                       f"({review_cta.get('tracking_host')})"),
        }
        return result

    if not row["approval_claim"]:
        return result

    # An approval that is not live. It has to be queued or suppressed, and if
    # fit was never assessed nobody can even say which.
    if not row["fit_reason"]:
        result["classification"] = UNKNOWN_FIT
        result["need_code"] = "unknown_fit_no_fit_reason"
        result["needs"] = ("approved with no Fit Reason recorded - GLP fit was never "
                           "assessed, so this cannot be routed to deploy or to suppression")
        return result

    accounting = account_for(row, ctx)
    if accounting:
        result["accounted_by"] = accounting
        return result

    if row["vertical"] == OUT_OF_SCOPE_VERTICAL:  # defensive: account_for covers it
        result["accounted_by"] = {"kind": "suppressed", "source": "sheet_vertical",
                                  "reason": "Vertical=out-of-scope"}
        return result

    result["classification"] = MISSED_DEPLOY
    result["need_code"] = ("missed_not_wire_in_ready" if not row["wire_in_ready"]
                           else "missed_wire_in_ready")
    invisible = ("" if row["wire_in_ready"] else
                 "; Wire-In Ready? is FALSE so the deploy machine's denominator never saw it")
    result["needs"] = (f"approved ({row['status']}) and in-scope (vertical={row['vertical']}, "
                       f"{row['fit_class']}) but not live, not queued for deploy, and not "
                       f"suppressed with a recorded reason{invisible} - needs a deploy "
                       "decision or a recorded suppression")
    return result


