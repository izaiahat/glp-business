def find_deploy_verification(row: dict[str, Any], site_match: dict[str, Any],
                             receipts: list[dict[str, Any]]) -> dict[str, Any] | None:
    """A `glp.deploy_live_verification.v1` receipt that names THIS program."""
    identity = row["identity"]
    network = norm(identity["network"])
    program_id = identity["program_id"].casefold()
    name = norm(identity["program_name"])
    site_program = norm(site_match.get("program"))
    for receipt in receipts:
        if str(receipt.get("sensor_status") or "").upper() != "PASS":
            continue
        for entry in receipt.get("programs") or []:
            matches = (
                (entry.get("sheet_row") and int(entry["sheet_row"]) == row["row"])
                or (program_id and network
                    and str(entry.get("provider_program_id") or "").casefold() == program_id
                    and norm(entry.get("network")) == network)
                or (name and norm(entry.get("program")) == name)
                or (site_program and norm(entry.get("slug")) == site_program)
            )
            if not matches:
                continue
            if not entry.get("live_url") or not entry.get("in_go_manifest"):
                continue
            return {
                **{key: entry[key] for key, _ in writer.SHEET_SYNC_MODES["deployed_live"].evidence_fields
                   if key in entry},
                "network": writer.canonical_network(entry.get("network")),
                "deploy_receipt_path": receipt["_path"],
                "live_url": entry["live_url"],
                "sensor_status": "PASS",
                "release": str(receipt.get("release") or ""),
                "verified_at_utc": str(receipt.get("captured_at_utc") or ""),
            }
    return None


def find_removal_receipt(row: dict[str, Any],
                         receipts: list[dict[str, Any]]) -> dict[str, Any] | None:
    """A `glp.site_paused_program_removal.v1` receipt that names THIS Sheet row."""
    identity = row["identity"]
    network = norm(identity["network"])
    program_id = identity["program_id"].casefold()
    for receipt in receipts:
        for entry in receipt.get("programs") or []:
            matches = (
                (entry.get("sheet_row") and int(entry["sheet_row"]) == row["row"])
                or (program_id and network
                    and str(entry.get("offer_id") or "").casefold() == program_id
                    and norm(entry.get("network")) == network)
            )
            if not matches:
                continue
            return {
                "removal_receipt_path": receipt["_path"],
                "release": str(receipt.get("release") or ""),
                "removed_at_utc": str(receipt.get("applied_at_utc") or ""),
            }
    return None


