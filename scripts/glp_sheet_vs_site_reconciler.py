def reconcile(sheet_values: list[list[Any]], site: dict[str, Any],
              ctx: dict[str, Any], run_id: str) -> dict[str, Any]:
    """Pure core: inputs in, classifications out. No I/O, no side effects."""
    rows = build_rows(sheet_values)
    assignments, ambiguous = match_site_programs(rows, site["programs"])

    results = [classify_row(row, assignments.get(row_num), ctx)
               for row_num, row in sorted(rows.items())]

    queue_rows = [queue_row_for(result, run_id)
                  for result in results if result.get("queue_row")]
    for result in results:
        result["queue_row"] = bool(result.get("queue_row"))

    counts = {name: 0 for name in CLASSES}
    for result in results:
        counts[result["classification"]] += 1
    non_consistent = [result for result in results
                      if result["classification"] != CONSISTENT]
    missed_by_fit: dict[str, int] = {}
    for result in results:
        if result["classification"] == MISSED_DEPLOY:
            key = result.get("fit_class") or "unassessed"
            missed_by_fit[key] = missed_by_fit.get(key, 0) + 1
    accounted: dict[str, int] = {}
    for result in results:
        source = (result.get("accounted_by") or {}).get("source")
        if source:
            accounted[source] = accounted.get(source, 0) + 1

    live_site_ids = sorted(pid for pid, program in site["programs"].items()
                           if program.get("on_live_site"))
    monetized_ids = sorted(pid for pid, program in site["programs"].items()
                           if program.get("on_live_site") or program.get("monetized_review_cta"))
    cta_only_ids = sorted(pid for pid, program in site["programs"].items()
                          if program.get("monetized_review_cta")
                          and not program.get("on_live_site"))
    return {
        "schema": SCHEMA,
        "run_id": run_id,
        "checked_at_utc": utc(),
        "sheet_id": writer.SHEET_ID,
        "sheet_tab": writer.TAB,
        "release": site["release"],
        "live_manifest": site["live_manifest"],
        "offline": site.get("offline", False),
        "rows_audited": len(results),
        "sheet_rows_total": max(len(sheet_values) - 1, 0),
        "site_programs_total": len(site["programs"]),
        "site_programs_live": len(live_site_ids),
        "site_programs_monetized": len(monetized_ids),
        "site_programs_monetized_by_review_cta_only": cta_only_ids,
        "tracking_host_allowlist": site.get("tracking_host_allowlist"),
        "review_cta_unrecognized_hosts": unrecognized_cta_hosts(site["programs"]),
        "class_counts": counts,
        "missed_deploy_by_fit_class": missed_by_fit,
        "accounted_by_source": accounted,
        "consistent_pct": (round(100.0 * counts[CONSISTENT] / len(results), 1)
                           if results else 100.0),
        "site_programs_unmatched": ambiguous,
        "queue_rows": queue_rows,
        "queue_row_count": len(queue_rows),
        "results": results,
        "non_consistent": non_consistent,
        "inputs": ctx["input_receipts"],
        "sheet_modified": False,
        "site_modified": False,
    }


