def review_cta_signal(release: Path, program_id: str, review_path: str | None,
                      canonical: dict[str, dict[str, Any]], redirects: dict[str, str],
                      allowlist: dict[str, Any],
                      contracts: dict[str, dict[str, Any]]) -> dict[str, Any] | None:
    """`monetized_review_cta`: does this program's live review page earn?

    Returns None when the program has no reachable rendered review page at all -
    which is a different fact from "the page is there and the CTA is held", and
    the classifier needs to be able to tell them apart.
    """
    page = rendered_review_page(release, program_id, review_path, canonical, redirects)
    if not page:
        return None
    try:
        html = page["page_path"].read_text(errors="replace")
    except OSError as exc:
        return {"review_route": page["review_route"], "resolved_route": page["resolved_route"],
                "resolution": page["resolution"], "page": repo_relative(page["page_path"]),
                "state": None, "monetized": False, "error": f"unreadable:{exc}"}

    candidates = []
    for element in cta_elements(html):
        host = urlsplit(element["href"]).hostname if element["href"] else None
        contract_program = (str(element.get("data_program") or "").strip()
                            if str(element.get("data_program") or "").strip() in contracts
                            else program_id)
        contract = contracts.get(contract_program)
        if contract:
            validation = validate_transparent_direct_element(
                element, contract, (allowlist.get("programs") or {}).get(contract_program))
            allowlisted = bool(validation.get("ok"))
        else:
            # Historical releases predate provider-page contracts. Keep their
            # old host-only audit path explicit; new releases never enter it.
            allowlisted = is_affiliate_tracking_host(host, allowlist["domains"])
            validation = {"ok": allowlisted, "validation": "legacy_release_host_allowlist",
                          "error": None if allowlisted else "legacy_tracking_host_unrecognized"}
        candidates.append({
            **element,
            "tracking_host": host,
            "tracking_host_allowlisted": allowlisted,
            "monetized": element["state"] == CTA_ACTIVE_STATE and allowlisted,
            "rail_validation": validation,
        })
    if not candidates:
        chosen: dict[str, Any] = {"state": None, "href": None, "link_mode": None,
                                  "data_program": None, "tracking_host": None,
                                  "tracking_host_allowlisted": False, "monetized": False}
    else:
        # Strongest first: a monetized CTA, else an active-but-unrecognised one,
        # else whatever the page declares (typically `held`).
        chosen = next((c for c in candidates if c["monetized"]),
                      next((c for c in candidates if c["state"] == CTA_ACTIVE_STATE),
                           candidates[0]))
    return {
        "review_route": page["review_route"],
        "resolved_route": page["resolved_route"],
        "resolution": page["resolution"],
        "page": repo_relative(page["page_path"]),
        "cta_elements": len(candidates),
        **chosen,
    }


def apply_monetization_signal(release: Path, programs: dict[str, dict[str, Any]]) -> dict[str, Any]:
    """Attach `review_cta` / `monetized_*` to every site program. Local reads only."""
    allowlist = read_tracking_host_allowlist(release)
    contracts = read_tracking_link_contracts(release)
    redirects = read_redirect_map(release)
    canonical = read_canonical_identity(release)
    for program_id, program in programs.items():
        signal = review_cta_signal(release, program_id, program.get("review_path"),
                                   canonical, redirects, allowlist, contracts)
        program["review_cta"] = signal
        program["monetized_review_cta"] = bool(signal and signal.get("monetized"))
        program["monetized_on_site"] = bool(program.get("on_live_site")
                                            or program["monetized_review_cta"])
    return {"tracking_host_allowlist": allowlist,
            "tracking_link_contracts": len(contracts),
            "redirect_rules": len(redirects),
            "canonical_identity_rows": len(canonical)}


def unrecognized_cta_hosts(programs: dict[str, dict[str, Any]]) -> list[dict[str, Any]]:
    """Active CTAs whose href host no affiliate network in the allowlist claims."""
    found = []
    for program_id, program in sorted(programs.items()):
        cta = program.get("review_cta") or {}
        if cta.get("state") != CTA_ACTIVE_STATE or cta.get("tracking_host_allowlisted"):
            continue
        found.append({
            "program": program_id,
            "review_page": cta.get("page"),
            "href": cta.get("href"),
            "tracking_host": cta.get("tracking_host"),
            "rail_validation": cta.get("rail_validation"),
            # A program already routed through /go still earns; the unrecognised
            # host is a note there, and the whole finding where it is not.
            "monetized_by_go_manifest": bool(program.get("on_live_site")),
        })
    return found


def read_site(offline: bool = False) -> dict[str, Any]:
    """The program set the site actually serves, release + deployed manifest.

    `on_live_site` is membership of the DEPLOYED /go/_manifest - the only thing
    a reader can actually reach. Release registry membership is carried
    separately so release-vs-deployed drift is visible rather than averaged in.

    `monetized_on_site` is the money question: the /go route OR a live
    transparent-direct affiliate CTA on the rendered review page. The two are
    kept separate on purpose - `on_live_site` still means exactly what it always
    meant, so nothing downstream silently re-reads as "has a /go route".
    """
    release = liveness.release_root()
    go = liveness.go_manifest_programs(release)
    registry = liveness.registry_live_programs(release)
    mapping = liveness.identity_map(release)

    live_manifest: dict[str, Any] = {"ok": False, "program_ids": [], "manifest_sha256": None}
    if not offline:
        response = liveness.http_get(liveness.LIVE_MANIFEST_URL)
        if response["ok"] and response["status"] == 200:
            try:
                payload = json.loads(response["body"])
                live_manifest = {"ok": True,
                                 "program_ids": sorted(payload.get("program_ids") or []),
                                 "manifest_sha256": payload.get("manifest_sha256")}
            except Exception as exc:  # noqa: BLE001
                live_manifest["error"] = f"unparseable:{exc}"
        else:
            live_manifest["error"] = f"http_{response.get('status')}:{response.get('error', '')}"
    if not offline and not live_manifest["ok"]:
        # The deployed manifest IS the definition of live. Guessing from the
        # release would silently reclassify every ghost and every stale row.
        raise SystemExit(f"live_manifest_unreadable:{live_manifest.get('error')}")

    live_ids = set(live_manifest["program_ids"]) if not offline else set(go["programs"])
    programs = {}
    for program_id in sorted(set(go["programs"]) | set(registry) | live_ids):
        registry_row = registry.get(program_id, {})
        display_name = (registry_row.get("display_name")
                        or (go["programs"].get(program_id) or {}).get("display_name"))
        identity = liveness.resolve_identity(program_id, display_name, mapping)
        programs[program_id] = {
            "program": program_id,
            "display_name": display_name,
            "network": identity.get("network") or "",
            "network_program_id": identity.get("network_program_id") or "",
            "review_path": registry_row.get("review_path"),
            "surfaces": registry_row.get("surfaces") or {},
            "on_live_site": program_id in live_ids,
            "in_release_go_manifest": program_id in go["programs"],
            "in_release_registry": program_id in registry,
        }
    monetization = apply_monetization_signal(release, programs)
    unrecognized = unrecognized_cta_hosts(programs)
    return {
        "release": str(release),
        "release_manifest_sha256": go.get("manifest_sha256"),
        "live_manifest": live_manifest,
        "offline": offline,
        "programs": programs,
        "unrecognized_tracking_hosts": unrecognized,
        **monetization,
    }


