def discord_text(receipt: dict[str, Any]) -> str:
    """Name every non-consistent row. Silent when the crawl is 100% clean."""
    counts = receipt["class_counts"]
    rows = receipt["non_consistent"]
    unmatched = [u for u in receipt["site_programs_unmatched"]
                 if u.get("monetized_on_site") or u.get("on_live_site")]
    if not rows and not unmatched:
        return ""
    lines = [
        f"**GLP sheet-vs-site reconcile** — {receipt['rows_audited']} rows vs "
        f"{receipt['site_programs_live']} live programs · {counts[CONSISTENT]} CONSISTENT "
        f"({receipt['consistent_pct']}%) · {receipt['queue_row_count']} queued (rows below "
        f"are `sheet row` + program)",
    ]
    for name in (STALE_STATUS, MISSED_DEPLOY, GHOST, UNKNOWN_FIT, BLANK_MALFORMED):
        group = [r for r in rows if r["classification"] == name]
        if not group:
            continue
        lines.append(f"__{name} ({len(group)})__")
        codes: dict[str, list[dict[str, Any]]] = {}
        for result in group:
            codes.setdefault(result.get("need_code") or "see_receipt", []).append(result)
        for code, members in codes.items():
            named = " · ".join(f"{m['row']} {clip(m['program'], 30)}" for m in members)
            sentence = NEED_SENTENCE.get(code, code)
            lines.append(f"{named}\n↳ {sentence}")
    if unmatched:
        lines.append("__SITE-UNMATCHED (" + str(len(unmatched)) + ")__ live site programs no "
                     "Sheet row claims: "
                     + ", ".join(u["program"] for u in unmatched))
    text = "\n".join(lines)
    if len(text) <= 1960:
        return text
    # Never truncate a row out of existence silently: drop the sentences first,
    # then say plainly that the detail moved to the receipt.
    terse = [lines[0]]
    for name in (STALE_STATUS, MISSED_DEPLOY, GHOST, UNKNOWN_FIT, BLANK_MALFORMED):
        group = [r for r in rows if r["classification"] == name]
        if group:
            terse.append(f"__{name} ({len(group)})__ "
                         + " · ".join(f"row {m['row']} {clip(m['program'], 30)}"
                                      for m in group))
    terse.append(f"Per-row detail: {receipt.get('receipt_path') or 'the run receipt'}")
    text = "\n".join(terse)
    return text if len(text) <= 1900 else text[:1890] + "…"


