def index_backfill_queue(items: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    """deploy-backfill-queue items keyed by sheet row and by identity."""
    index: dict[str, dict[str, Any]] = {}
    for item in items:
        evidence = item.get("evidence") or {}
        sheet_row = evidence.get("sheet_row")
        if sheet_row:
            index.setdefault(f"row:{sheet_row}", item)
        network = norm(item.get("network"))
        program_id = str(item.get("program_id") or "").strip().casefold()
        if network and program_id:
            index.setdefault(f"id:{network}:{program_id}", item)
        name = norm(item.get("program_name"))
        if name:
            index.setdefault(f"name:{name}", item)
    return index


def index_wire_backlog(plan: dict[str, Any]) -> dict[int, dict[str, Any]]:
    """Sheet row -> the deploy machine's own disposition for it."""
    index: dict[int, dict[str, Any]] = {}
    for bucket, disposition in (("queue", "queued_for_deploy"),
                                ("sister_dark", "suppressed_sister_dark"),
                                ("already_wired", "already_wired"),
                                ("fail_closed_unmapped", "fail_closed_unmapped")):
        for entry in plan.get(bucket) or []:
            row = entry.get("sheet_row")
            if not row:
                continue
            index.setdefault(int(row), {
                "bucket": bucket,
                "disposition": entry.get("disposition") or disposition,
                "reason": entry.get("reason"),
                "display_name": entry.get("display_name"),
            })
    return index


def index_suppression(entries: dict[str, Any]) -> dict[str, dict[str, Any]]:
    index: dict[str, dict[str, Any]] = {}
    for key, entry in entries.items():
        network = norm(entry.get("network") or key.split(":", 1)[0])
        campaign = str(entry.get("campaign_id") or "").strip().casefold()
        if network and campaign:
            index.setdefault(f"id:{network}:{campaign}", entry)
        for name in (entry.get("advertiser_name"), entry.get("campaign_title")):
            if norm(name):
                index.setdefault(f"name:{network}:{norm(name)}", entry)
    return index


def account_for(row: dict[str, Any], ctx: dict[str, Any]) -> dict[str, Any] | None:
    """Why is this approved, not-live row legitimately not on the site?

    Returns the recorded reason, or None - and None is the whole point of the
    job: it means nobody, anywhere, wrote down why this approval is idle.
    """
    identity = row["identity"]
    padded = row["padded"]
    status = row["status"]
    network = norm(identity["network"])
    program_id = identity["program_id"].casefold()
    name = norm(identity["program_name"])
    row_num = row["row"]

    if status in SELF_SUPPRESSING_STATUS:
        return {"kind": "suppressed", "source": "sheet_status",
                "reason": f"status={status} is its own recorded reason"}

    if str(padded[COL_VERTICAL]).strip() == OUT_OF_SCOPE_VERTICAL:
        return {"kind": "suppressed", "source": "sheet_vertical",
                "reason": "Vertical=out-of-scope (recorded fit decision)"}

    suppression = ctx["suppression"]
    for key in (f"id:{network}:{program_id}" if program_id else "",
                f"name:{network}:{name}" if name else ""):
        if key and key in suppression:
            entry = suppression[key]
            return {"kind": "suppressed", "source": "relationship_suppression_ledger",
                    "reason": clip(entry.get("reason"), 240),
                    "decided_at_utc": entry.get("decided_at_utc")}

    backfill = ctx["backfill"]
    for key in (f"row:{row_num}",
                f"id:{network}:{program_id}" if program_id else "",
                f"name:{name}" if name else ""):
        if key and key in backfill:
            item = backfill[key]
            classification = str(item.get("classification") or "").upper()
            if classification in BACKFILL_SUPPRESSED:
                return {"kind": "suppressed", "source": "deploy_backfill_queue",
                        "reason": f"{classification}: {clip(item.get('resolution') or item.get('fit'), 200)}"}
            if classification in BACKFILL_QUEUED:
                return {"kind": "queued", "source": "deploy_backfill_queue",
                        "reason": f"{classification} in deploy-backfill-queue.json"}

    backlog = ctx["wire_backlog"].get(row_num)
    if backlog:
        if backlog["bucket"] == "queue":
            return {"kind": "queued", "source": "wire_backlog_plan",
                    "reason": "in the B2 wire-backlog plan queue"}
        if backlog["bucket"] == "sister_dark":
            return {"kind": "suppressed", "source": "wire_backlog_plan",
                    "reason": f"sister_dark: {clip(backlog.get('disposition'), 120)}"}
        # `fail_closed_unmapped` and `already_wired` are NOT dispositions. The
        # first is the deploy machine admitting it could not map the row; the
        # second is a claim this job is here to verify. Neither accounts for an
        # idle approval, so both fall through to MISSED-DEPLOY on purpose.
    return None


