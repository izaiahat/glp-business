#!/usr/bin/env python3
"""Machine 6 - the weekly sheet-vs-site reconciler (the last audit layer).

WHY THIS EXISTS
---------------
The 2026-08-18 affiliate architecture makes the governed Google Sheet the single
source of truth and lets exactly ONE job write it. Every other machine reads the
Sheet and queues its changes. That protects the Sheet from corruption, but it
does not answer the operator's actual question, which is the *weekly sheet
crawl*:

    every approved + GLP-fit provider must be LIVE on the site,
    or QUEUED for deploy,
    or SUPPRESSED with a recorded reason.

Nothing else was asking that question end to end. The liveness audit (machine 5)
walks the SITE and asks the networks whether each live program still runs - it
never looks at a Sheet row that never made it to the site. The deploy machine
(machine 4) walks the Sheet diff since its last run - it never re-examines a row
it skipped six days ago. So an approval could sit in the Sheet forever, fit,
approved, invisible, and no machine would ever say the word.

This job says the word. It audits EVERY Sheet row against reality and gives each
one exactly one class:

  CONSISTENT       the Sheet's claim and reality agree, or the row is approved
                   and legitimately accounted for (queued, or suppressed with a
                   reason someone actually recorded)
  MISSED-DEPLOY    approved + GLP-fit, not live, not queued, not suppressed -
                   money on the floor that nothing is working on
  GHOST            the program IS live on the site, but the Sheet does not say
                   live - the Sheet under-claims reality
  STALE-STATUS     the Sheet claims live (status or the Wired Live? checkbox)
                   and the program is not earning on the site - the Sheet
                   over-claims
  UNKNOWN-FIT      approved, not live, and fit was never assessed (no Fit Reason)
  BLANK-MALFORMED  the row's own schema is broken enough that its claims cannot
                   be trusted

WHAT "LIVE ON THE SITE" MEANS (the `monetized_review_cta` signal)
-----------------------------------------------------------------
The first production runs defined it as membership of the deployed /go manifest
and nothing else. That was wrong, and it produced a permanent false positive:
five programs (Direct Meds, Sprout Health, MangoRx, Coivas, SHED) earn through a
`transparent_direct` affiliate CTA rendered straight onto their review page, with
no /go route at all - a recorded production-authority decision, not an oversight.
The reconciler re-flagged all five STALE-STATUS every Monday and the only honest
fix was to teach the site model the second surface.

A program is MONETIZED ON SITE when either

  * it has a /go route in the DEPLOYED manifest, or
  * the review page a reader actually lands on carries an active transparent-direct
    affiliate anchor whose href validates against that program's canonical rail
    and whose CTA class/rel/data markers are complete.

Both halves matter. `data-affiliate-state="held"` is the site's own word for a
deliberately de-linked CTA (Measured, TRT Nation) and must never clear a row. And
an active CTA pointing at a host nobody recognises is not proof of attribution -
it is reported as `review_cta_unrecognized_tracking_host` rather than passed.

The per-program host projection is sourced from the release's own
`data/tracking-allowed-hosts.json`, generated by
`glp_affiliate_link_rails.program_allowed_hosts`. The verifier uses that same
canonical module for rail-specific parameters (including Trackdesk's
linkId/sourceId/tenantId). Historical releases without the projection retain a
named legacy approved-registry fallback rather than silently borrowing it.

"The page a reader actually lands on" resolves the release's exact-path redirect
map and the registry's own `canonical_identity` alias declaration, because a
Sheet row can name an alias whose route 301s onto the canonical merchant record
(row 323 SHED -> /reviews/shed/ -> /reviews/shedrx/). A resolved route is only
accepted if it is still a review page: a program whose route was retired onto a
category page must not inherit that page's CTAs.

DISCIPLINE
----------
* READ-ONLY on the Sheet and on the site. This job holds no write path to
  either; it never calls the governed writer, it never touches a release.
* Its only outputs are (a) sheet_update_queue rows, (b) a JSON receipt on disk,
  (c) a Discord line. Corrections are QUEUED for the one writer, never applied.
* A queue row is emitted only where a class maps to a governed writer mode AND
  an evidence file that already exists on disk supports it:
      GHOST         -> `deployed_live`, citing a `glp.deploy_live_verification.v1`
                       receipt that names this program with sensor_status PASS
      STALE-STATUS  -> `removed`, citing a `glp.site_paused_program_removal.v1`
                       receipt that names this program's Sheet row
  Everything else - every MISSED-DEPLOY, every UNKNOWN-FIT, every GHOST with no
  verification receipt - goes to the report and to Discord. This job never
  invents an approval, never fabricates a deploy receipt, and never asserts a
  fact it did not read off disk or off the wire.
* Silence means clean: if every audited row is CONSISTENT there is no Discord
  card. Anything else is named out loud, with the row number and what it needs.

Exit 0 = the audit ran and produced classifications (including bad ones).
Exit non-zero = the audit itself failed and its answer cannot be trusted.
"""
