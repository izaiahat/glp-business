@pytest.mark.parametrize("damage", [
    "leading-js", "wrong-export", "wrong-suffix", "trailing-js", "second-object",
    "javascript-expression", "duplicate-key", "nested-duplicate-key", "nan", "infinity",
    "invalid-utf8", "truncated-json", "array",
])
def test_wrapper_parses_strict_json_without_executing_js(synthetic_release, damage):
    fixture = synthetic_release
    body = fixture.module.read_bytes()
    if damage == "leading-js":
        body = b"throw new Error('synthetic');\n" + body
    elif damage == "wrong-export":
        body = body.replace(b"GO_RUNTIME_MANIFEST", b"OTHER_MANIFEST")
    elif damage == "wrong-suffix":
        body = body[:-2] + b"\n"
    elif damage == "trailing-js":
        body += b"throw new Error('synthetic');\n"
    elif damage == "second-object":
        body = body[:-3] + b" {});\n"
    elif damage == "javascript-expression":
        body = PREFIX + b"{\"programs\": process.exit(1)});\n"
    elif damage == "duplicate-key":
        body = PREFIX + b'{"schema":"wrong",' + body[len(PREFIX) + 1:]
    elif damage == "nested-duplicate-key":
        body = body.replace(b'"synthetic-allowed": {}', b'"synthetic-allowed": {"x":1,"x":2}')
    elif damage in {"nan", "infinity"}:
        body = PREFIX + b'{"invalid":' + (b"NaN" if damage == "nan" else b"Infinity") + b"," + body[len(PREFIX) + 1:]
    elif damage == "invalid-utf8":
        body = body.replace(b"synthetic-allowed", b"synthetic-\xff")
    elif damage == "truncated-json":
        body = PREFIX + b'{"schema":});\n'
    else:
        body = PREFIX + b"[]);\n"
    fixture.module.write_bytes(body)
    fixture.seal()
    with pytest.raises(RuntimeError, match="affiliate_release_runtime_manifest_.*invalid"):
        collector._bound_affiliate_release(fixture.control)
    fixture.http.assert_not_called()


@pytest.mark.parametrize("damage", [
    "status", "schema", "digest", "module-byte-digest", "missing-member", "extra-member",
    "different-member", "duplicate-member", "string-members", "numeric-member", "empty-member",
    "missing-members", "null-members", "array", "invalid-json", "duplicate-key", "nan",
])
def test_endpoint_must_match_embedded_digest_and_membership(synthetic_release, damage):
    fixture = synthetic_release
    live = copy.deepcopy(fixture.served)
    status = 200
    if damage == "status":
        status = 503
    elif damage == "schema":
        live["schema"] = "wrong"
    elif damage in {"digest", "module-byte-digest"}:
        live["manifest_sha256"] = "0" * 64 if damage == "digest" else sha(fixture.module.read_bytes())
    elif damage == "missing-member":
        live["program_ids"].pop()
    elif damage == "extra-member":
        live["program_ids"].append("synthetic-other")
    elif damage == "different-member":
        live["program_ids"][0] = "synthetic-other"
    elif damage == "duplicate-member":
        live["program_ids"].append(live["program_ids"][0])
    elif damage == "string-members":
        live["program_ids"] = "synthetic-allowed"
    elif damage == "numeric-member":
        live["program_ids"][0] = 123
    elif damage == "empty-member":
        live["program_ids"][0] = ""
    elif damage == "missing-members":
        del live["program_ids"]
    elif damage == "null-members":
        live["program_ids"] = None
    elif damage == "array":
        live = []
    body = json.dumps(live)
    if damage == "invalid-json":
        body = "{"
    elif damage == "duplicate-key":
        body = '{"schema":"wrong",' + body[1:]
    elif damage == "nan":
        body = '{"invalid":NaN,' + body[1:]
    fixture.http.return_value = status, body
    with pytest.raises(RuntimeError, match="affiliate_deployed_release_manifest_mismatch"):
        collector._bound_affiliate_release(fixture.control)
    fixture.http.assert_called_once()


def test_legacy_artifact_and_different_staging_schema_cannot_fallback(synthetic_release):
    fixture = synthetic_release
    legacy = fixture.release / "artifacts/ops/worker-manifest.staging.json"
    write_json(legacy, fixture.local)
    write_json(fixture.release / "data/worker-manifest.staging.json", {"schema": "different-staging-schema"})
    assert sha(legacy.read_bytes()) != sha((fixture.release / "data/worker-manifest.staging.json").read_bytes())
    manifest = json.loads(fixture.manifest.read_text())
    manifest["release_rows"][0] = {"path": str(legacy.relative_to(fixture.release)), "sha256": sha(legacy.read_bytes())}
    write_json(fixture.manifest, manifest)
    pointer = json.loads(fixture.pointer.read_text())
    pointer["manifest"]["sha256"] = sha(fixture.manifest.read_bytes())
    write_json(fixture.pointer, pointer)
    fixture.module.unlink()
    with pytest.raises(RuntimeError, match=f"affiliate_release_authority_drift:{MODULE}"):
        collector._bound_affiliate_release(fixture.control)
    fixture.http.assert_not_called()


