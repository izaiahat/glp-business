MODULE = "functions/go/program-manifest.js"
AUTHORITIES = (MODULE, "data/program-registry.json", "data/go-runtime-promotion-authority.json")
PREFIX = (b"// Generated by scripts/build-staging.mjs. Do not edit by hand.\n"
          b"export const GO_RUNTIME_MANIFEST = Object.freeze(")


def sha(body):
    return hashlib.sha256(body).hexdigest()


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, sort_keys=True) + "\n", encoding="utf-8")


@pytest.fixture
def synthetic_release(tmp_path, monkeypatch):
    release = tmp_path / "release"
    module = release / MODULE
    module.parent.mkdir(parents=True)
    local = {
        "schema": "affiliate-worker-staging-v3-registry",
        "program_registry_schema": "site-program-registry-v1",
        "site_profile": "glp-clinic-scout",
        "internal_fallback": "https://glpclinicscout.com/providers/",
        "manifest_sha256": sha(b"synthetic staging input, not retained release bytes"),
        "programs": {name: {} for name in ("synthetic-allowed", "synthetic-withheld", "synthetic-unknown")},
    }
    module.write_bytes(PREFIX + json.dumps(local).encode() + b");\n")
    write_json(release / AUTHORITIES[1], {"programs": [
        {"program_id": name, "commercial_state": "active", "review_path": f"/reviews/{name}/"}
        for name in local["programs"]
    ]})
    write_json(release / AUTHORITIES[2], {"programs": {
        "synthetic-allowed": {"promotion_authorized": True, "status": "VERIFIED"},
        "synthetic-withheld": {"promotion_authorized": False, "status": "WITHHELD"},
    }})
    manifest, final, pointer = (tmp_path / name for name in ("manifest.json", "final.json", "pointer.json"))
    write_json(final, {"synthetic": True, "status": "PASS"})

    def seal():
        write_json(manifest, {"release_rows": [
            {"path": name, "sha256": sha((release / name).read_bytes())} for name in AUTHORITIES
        ]})
        write_json(pointer, {
            "status": "PASS", "release_root": str(release),
            "manifest": {"path": str(manifest), "sha256": sha(manifest.read_bytes())},
            "final_receipt": {"path": str(final), "sha256": sha(final.read_bytes())},
        })

    seal()
    served = {key: local[key] for key in ("schema", "manifest_sha256")}
    served["program_ids"] = list(reversed(local["programs"]))
    http = Mock(return_value=(200, json.dumps(served)))
    monkeypatch.setattr(collector, "BUSINESS", tmp_path)
    monkeypatch.setattr(collector, "_http_text", http)
    control = {"affiliate_obligations": {
        "release_pointer": "pointer.json", "deployed_manifest": "https://glpclinicscout.com/go/_manifest",
    }, "affiliate_routes": ["/providers/"]}
    return SimpleNamespace(release=release, module=module, local=local, manifest=manifest,
                           final=final, pointer=pointer, seal=seal, served=served, http=http, control=control)


def test_sealed_generated_module_binds_embedded_hash_and_exact_membership(synthetic_release):
    fixture = synthetic_release
    assert not (fixture.release / "artifacts/ops/worker-manifest.staging.json").exists()
    assert sha(fixture.module.read_bytes()) != fixture.local["manifest_sha256"]
    assert collector._bound_affiliate_release(fixture.control) == (
        fixture.release, set(fixture.local["programs"]))
    fixture.http.assert_called_once_with("https://glpclinicscout.com/go/_manifest")


@pytest.mark.parametrize("key", ["manifest", "final_receipt"])
@pytest.mark.parametrize("damage", ["missing", "changed", "absent-file", "missing-path", "missing-digest"])
def test_pointer_seals_refuse_before_synthetic_transport(synthetic_release, key, damage):
    fixture = synthetic_release
    pointer = json.loads(fixture.pointer.read_text())
    if damage == "missing":
        del pointer[key]
    elif damage == "changed":
        Path(pointer[key]["path"]).write_bytes(b"changed synthetic sealed bytes")
    elif damage == "absent-file":
        Path(pointer[key]["path"]).unlink()
    else:
        del pointer[key]["path" if damage == "missing-path" else "sha256"]
    write_json(fixture.pointer, pointer)
    with pytest.raises(RuntimeError, match=f"affiliate_release_{key}_"):
        collector._bound_affiliate_release(fixture.control)
    fixture.http.assert_not_called()


@pytest.mark.parametrize("name", AUTHORITIES)
@pytest.mark.parametrize("damage", ["missing-seal", "changed-seal", "changed-bytes", "absent-file"])
def test_all_three_authority_seals_refuse_before_transport(synthetic_release, name, damage):
    fixture = synthetic_release
    manifest = json.loads(fixture.manifest.read_text())
    if damage == "missing-seal":
        manifest["release_rows"] = [row for row in manifest["release_rows"] if row["path"] != name]
    elif damage == "changed-seal":
        next(row for row in manifest["release_rows"] if row["path"] == name)["sha256"] = "0" * 64
    elif damage == "changed-bytes":
        (fixture.release / name).write_bytes(b"changed synthetic authority bytes")
    else:
        (fixture.release / name).unlink()
    write_json(fixture.manifest, manifest)
    pointer = json.loads(fixture.pointer.read_text())
    pointer["manifest"]["sha256"] = sha(fixture.manifest.read_bytes())
    write_json(fixture.pointer, pointer)
    with pytest.raises(RuntimeError, match=f"affiliate_release_authority_drift:{name}"):
        collector._bound_affiliate_release(fixture.control)
    fixture.http.assert_not_called()


