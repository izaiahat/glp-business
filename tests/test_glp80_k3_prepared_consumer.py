def load_file(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def readonly_producer():
    # Compile only the dependency closure of these read-only native validators
    # and the inert pointer-intent constructor, never the complete carrier.
    path = SCRIPTS / 'glp_deploy_glp34_authority_v1.py'
    tree = ast.parse(path.read_text())
    definitions = {}
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            definitions[node.name] = node
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for target in targets:
                if isinstance(target, ast.Name):
                    definitions[target.id] = node
    needed = {'current_prepared', 'package_tree', 'package_build_receipt',
              'current_route_specs', 'current_pointer_intent', 'CURRENT_ROLLBACK',
              'CURRENT_PROMOTION_ROOT_SHA256', 'CURRENT_PROMOTION_ROLLED_BACK_SUCCESSOR_SHA256',
              'CURRENT_PROMOTION_POST_IDENTITY_TERMINAL_SHA256', 'CURRENT_TOOLCHAIN'}
    while True:
        expanded = needed | {n.id for key in needed for n in ast.walk(definitions[key])
                             if isinstance(n, ast.Name) and n.id in definitions}
        if expanded == needed:
            break
        needed = expanded
    nodes = [n for n in tree.body if isinstance(n, (ast.Import, ast.ImportFrom)) or
             any(n is definitions[k] for k in needed)]
    module = types.ModuleType('glp_deploy_glp34_authority_v1')
    module.__file__ = str(path)
    exec(compile(ast.Module(body=nodes, type_ignores=[]), str(path), 'exec'), module.__dict__)
    # Synthetic promotion receipts are expressly not native approval evidence.
    def forbidden(*a, **k):
        raise AssertionError('promotion/provider execution forbidden')
    module.current_promotion_source = forbidden
    module.current_promotion_post_identity_source = forbidden
    return module


