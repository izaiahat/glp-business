def test_exact_pin_cohort_and_preimport_drift(tmp_path, monkeypatch):
    daily = load_file(PACKAGE / 'daily_evidence_refresh.py', 'k3_test_pins')
    pins = json.loads((PACKAGE / 'SOURCE-PINS.json').read_text())
    # Rebase exact deployment path names only into this clean checkout.
    required = set(pins['sources'])
    for value in required:
        actual = ROOT / Path(value).relative_to('/home/ubuntu/business')
        assert daily.sha(actual) == pins['sources'][value]
    monkeypatch.setattr(daily, 'sha', lambda p: hashlib.sha256((ROOT / Path(p).relative_to('/home/ubuntu/business')).read_bytes()).hexdigest()
                        if str(p).startswith('/home/ubuntu/business/') and not str(p).startswith(str(ROOT)) else hashlib.sha256(Path(p).read_bytes()).hexdigest())
    daily.check_pins()
    broken = json.loads(json.dumps(pins))
    schema = '/home/ubuntu/business/scripts/glp_current_content_base_schema.py'
    broken['sources'][schema] = 'a2a65183b8f501213e9f03730a64101e141c79c43035009a7bf7b28c0a676e46'
    changed = tmp_path / 'SOURCE-PINS.json'
    changed.write_text(json.dumps(broken))
    with pytest.raises(RuntimeError, match='SOURCE_PIN_DRIFT:.*schema'):
        daily.check_pins(changed)
    wrapper = load_file(ROOT / 'ops/hermes-cron-scripts/glp_evidence_refresh_daily.py', 'k3_wrapper_test')
    assert wrapper.BASE == Path('/home/ubuntu/business/ops/glp/evidence-refresh-k3')
    for name, digest in wrapper.PINS.items():
        assert hashlib.sha256((PACKAGE / name).read_bytes()).hexdigest() == digest
    monkeypatch.setattr(wrapper, 'BASE', tmp_path)
    monkeypatch.setattr(wrapper.os, 'execv', lambda *a: pytest.fail('exec forbidden'))
    assert wrapper.main() == 2
    manifest = json.loads((ROOT / 'ops/rebuild-source-manifest.json').read_text())
    cohort = [str(p.relative_to(ROOT)) for p in PACKAGE.iterdir() if p.is_file()]
    cohort += ['.gitignore', '.github/workflows/glp80-k3-source.yml',
               'ops/hermes-cron-scripts/glp_evidence_refresh_daily.py',
               'tests/test_glp80_k3_prepared_consumer.py']
    cohort += [str(Path(p).relative_to('/home/ubuntu/business')) for p in pins['sources']]
    for rel in cohort:
        assert manifest['files'][rel]['sha256'] == hashlib.sha256((ROOT / rel).read_bytes()).hexdigest(), rel
