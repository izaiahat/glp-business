def k3_fixture(consumer, tmp_path, monkeypatch, prepared):
    daily, weekly, fixture = consumer
    _, flagship, pointer, pointer_path = fixture(tmp_path, monkeypatch, prepared)
    release = Path(pointer['release_root'])
    if not prepared:
        # K3's genuine legacy manifest uses bytes rows, not native size rows.
        manifest = json.loads(Path(pointer['manifest']['path']).read_text())
        rows = [{'path': str(p.relative_to(release)), 'bytes': p.stat().st_size,
                 'sha256': daily.sha(p)} for p in sorted(release.rglob('*')) if p.is_file()]
        manifest['release_rows'] = rows
        manifest['release_tree_sha256'] = daily.closure(rows)
        pointer['release_tree_sha256'] = daily.closure(rows)
        pointer['manifest']['sha256'] = ns_write(Path(pointer['manifest']['path']), manifest)
        receipt = json.loads(Path(pointer['final_receipt']['path']).read_text())
        receipt['immutable_closure']['release_tree_sha256'] = pointer['release_tree_sha256']
        receipt['evidence_sha256'] = {Path(pointer['manifest']['path']).name: pointer['manifest']['sha256']}
        pointer['final_receipt']['sha256'] = ns_write(Path(pointer['final_receipt']['path']), receipt)
        ns_write(pointer_path, pointer)
    return daily, weekly, pointer, pointer_path, flagship / 'releases'


def ns_write(path, value):
    path.write_text(json.dumps(value, sort_keys=True))
    return hashlib.sha256(path.read_bytes()).hexdigest()


def test_native_prepared_consumer_and_post_consumption_drift(consumer, tmp_path, monkeypatch):
    daily, weekly, pointer, path, releases = k3_fixture(consumer, tmp_path, monkeypatch, True)
    bound = daily.binding(path, releases)
    assert bound['pointer'] == pointer
    assert len(bound['prepared_binding']['files']) == 7  # synthetic receipt hashes share a successor path
    assert str(Path(pointer['release_root']).parent / 'PREPARED.json') in bound['prepared_binding']['files']
    daily.unchanged(bound)
    dependency = Path(pointer['release_root']).parent / 'PREPARED.json'
    original = dependency.read_bytes()
    dependency.write_bytes(original + b'\n')
    with pytest.raises(RuntimeError, match='(?i)prepared|POINTER_CHAIN'):
        daily.unchanged(bound)
    dependency.write_bytes(original)
    # Rebind the restored fixture identity, then alter only compiled runtime.
    rebound = daily.binding(path, releases)
    worker = dependency.parent / 'deploy-public/_worker.js'
    worker.write_bytes(b'altered worker\n')
    with pytest.raises(RuntimeError, match='(?i)prepared|registered'):
        daily.unchanged(rebound)


