"""Disjoint current-base composition for review intake, NEVER a live writer.

Packets must have been regenerated by review_evidence against the bound base.
Native whole-document validators run again; unrelated stale rows still refuse.
"""
import copy
import json
from pathlib import Path
import subprocess


DERIVED = {'/therapeutic_taxonomy/expected_counts', '/provider_dynamic_profiles/expected_counts'}
TAX_IDENTITY = ('program_id', 'registry_program_id', 'classification_state', 'commercial_link_state', 'render_label')
PROFILE_IDENTITY = ('program_id', 'registry_program_ids', 'provider', 'aliases', 'version')


def merge_packets(er, release, rows):
    paths = [release / 'data' / n for n in ('program-registry.json', 'provider-pricing-matrix.json')]
    original = [er.read(p) for p in paths]
    merged = copy.deepcopy(original)
    consumed, owners = {}, set()
    for row in rows:
        if row['status'] != 'PACKET_READY':
            continue
        pid = row['program_id']
        if 'fella' in pid or pid in owners:
            raise RuntimeError('EXCLUDED_OR_DUPLICATE_OWNER:' + pid)
        owners.add(pid)
        packet_path = Path(row['packet_path'])
        patch_path = packet_path.with_name('DATA-PATCH.json')
        consumed.update({str(p): er.sha(p) for p in (packet_path, patch_path)})
        packet, patch = er.read(packet_path), er.read(patch_path)
        if packet.get('status') != 'PACKET_READY' or packet.get('program_id') != pid:
            raise RuntimeError('PACKET_NOT_READY:' + pid)
        if packet.get('depends_on'):
            # Canonical patch already owns the alias. Do not apply twice.
            dep = packet['depends_on']
            if not any(r['program_id'] == dep['program_id'] and r['status'] == 'PACKET_READY' for r in rows):
                raise RuntimeError('ALIAS_DEPENDENCY_NOT_READY')
            for name in ('packet', 'patch'):
                if er.sha(dep[name + '_path']) != dep[name + '_sha256']:
                    raise RuntimeError('ALIAS_DEPENDENCY_DRIFT')
            if any(t['operations'] for t in patch['targets']):
                raise RuntimeError('ALIAS_DUPLICATE_OPERATIONS')
            continue
        aliases = [a['render_id'] for a in original[0]['provider_dynamic_profiles']['profiles'][pid]['aliases']]
        tax_ids = [pid, *aliases]
        if {t['path'] for t in patch['targets']} != {str(p) for p in paths} or len(patch['targets']) != 2:
            raise RuntimeError('PATCH_TARGET_SET_INVALID')
        for i, path in enumerate(paths):
            target = next(t for t in patch['targets'] if t['path'] == str(path))
            if er.sha(path) != target['source_sha256']:
                raise RuntimeError('PATCH_BASE_DRIFT')
            proposed = er.apply_patch(original[i], target['operations'])
            permitted = copy.deepcopy(original[i])
            if i == 0:
                for tid in tax_ids:
                    before = original[0]['therapeutic_taxonomy']['programs'][tid]
                    after = proposed['therapeutic_taxonomy']['programs'][tid]
                    if any(before.get(k) != after.get(k) for k in TAX_IDENTITY):
                        raise RuntimeError('TAXONOMY_AUTHORITY_MUTATION')
                    if merged[0]['therapeutic_taxonomy']['programs'][tid] != before:
                        raise RuntimeError('OVERLAPPING_TAXONOMY_OWNER')
                    permitted['therapeutic_taxonomy']['programs'][tid] = copy.deepcopy(after)
                    merged[0]['therapeutic_taxonomy']['programs'][tid] = copy.deepcopy(after)
                before = original[0]['provider_dynamic_profiles']['profiles'][pid]
                after = proposed['provider_dynamic_profiles']['profiles'][pid]
                if any(before.get(k) != after.get(k) for k in PROFILE_IDENTITY):
                    raise RuntimeError('PROFILE_IDENTITY_MUTATION')
                permitted['provider_dynamic_profiles']['profiles'][pid] = copy.deepcopy(after)
                merged[0]['provider_dynamic_profiles']['profiles'][pid] = copy.deepcopy(after)
                authorities = original[0]['therapeutic_taxonomy']['authorities']
                for key, value in proposed['therapeutic_taxonomy']['authorities'].items():
                    if key in authorities:
                        continue
                    current = merged[0]['therapeutic_taxonomy']['authorities'].get(key)
                    if current is not None and current != value:
                        raise RuntimeError('AUTHORITY_COLLISION')
                    permitted['therapeutic_taxonomy']['authorities'][key] = copy.deepcopy(value)
                    merged[0]['therapeutic_taxonomy']['authorities'][key] = copy.deepcopy(value)
                for section in ('therapeutic_taxonomy', 'provider_dynamic_profiles'):
                    permitted[section]['expected_counts'] = proposed[section]['expected_counts']
            else:
                if pid in proposed['providers']:
                    permitted['providers'][pid] = copy.deepcopy(proposed['providers'][pid])
                    merged[1]['providers'][pid] = copy.deepcopy(proposed['providers'][pid])
                permitted['coverage'] = proposed['coverage']
            if permitted != proposed:
                raise RuntimeError('PATCH_OUTSIDE_OWNED_FACTS')
    return *merged, consumed


def compose(d, er, bound, rows, out):
    """Called only after source-bound review regeneration under the daily lock."""
    d.unchanged(bound)
    if not any(r['status'] == 'PACKET_READY' for r in rows):
        return {'status': 'BLOCKED_NO_READY_PACKETS', 'combined_patch': None}
    release = Path(bound['pointer']['release_root'])
    registry, matrix, consumed = merge_packets(er, release, rows)
    # Derive once after disjoint composition, then run real entire-base gates.
    code = '''import fs from 'node:fs';
import {deriveFacetCounts,reconcileTherapeuticTaxonomyWireIn} from './src/therapeutic-taxonomy.mjs';
import {deriveDynamicFacetCounts,validateProviderDynamicProfiles} from './src/provider-dynamic-profiles.mjs';
const {registry:r,matrix:m}=JSON.parse(fs.readFileSync(0,'utf8'));
r.therapeutic_taxonomy.expected_counts=deriveFacetCounts(r.therapeutic_taxonomy.programs);
r.provider_dynamic_profiles.expected_counts=deriveDynamicFacetCounts(r.provider_dynamic_profiles.profiles);
const rows=Object.values(m.providers).flatMap(p=>p.medications||[]);
m.coverage={medication_rows:rows.length,providers_pricing_unavailable:Object.values(m.providers).filter(p=>!p.medications?.length).length,providers_total:Object.keys(m.providers).length,providers_with_evidenced_pricing:Object.values(m.providers).filter(p=>p.medications?.length).length,rows_with_intro_month_1:rows.filter(r=>r.month_1_basis==='intro').length};
reconcileTherapeuticTaxonomyWireIn({registry:r,profileId:'glp-clinic-scout',pages:JSON.parse(fs.readFileSync('data/money-page-specs.json')).pages,quizConfig:JSON.parse(fs.readFileSync('data/quiz-config.json'))});
validateProviderDynamicProfiles(r,'glp-clinic-scout',{asOf:new Date()});
process.stdout.write(JSON.stringify({registry:r,matrix:m}));'''
    run = subprocess.run(['node', '--input-type=module', '-e', code], cwd=release,
                         input=json.dumps({'registry': registry, 'matrix': matrix}),
                         text=True, capture_output=True, timeout=90)
    d.unchanged(bound)
    for path, digest in consumed.items():
        if er.sha(path) != digest:
            raise RuntimeError('COMPOSITION_INPUT_DRIFT')
    if run.returncode:
        return {'status': 'BLOCKED_COMBINED_VALIDATION', 'combined_patch': None,
                'condition': run.stderr[-4000:], 'inputs': consumed}
    verified = json.loads(run.stdout)
    targets = []
    for name, value in [('program-registry.json', verified['registry']), ('provider-pricing-matrix.json', verified['matrix'])]:
        path = release / 'data' / name
        targets.append({'path': str(path), 'source_sha256': er.sha(path),
                        'operations': er.diff(er.read(path), value)})
    patch = out / 'COMBINED-PATCH.json'
    d.put(patch, {'schema': 'k3-current-base-disjoint-intake-v1', 'binding': bound,
                 'inputs': consumed, 'targets': targets, 'applied_to_candidate': False,
                 'adoption_requirements': ['recheck full binding and input hashes', 'independent review',
                                         'governed candidate-writer intake; no direct live apply']})
    return {'status': 'COMPOSED_PENDING_GOVERNED_ADOPTION', 'combined_patch': str(patch),
            'combined_patch_sha256': er.sha(patch), 'inputs': consumed}
